// TestProjectModuleRenamePreflightWriteFailures prevents predictable failures from leaving mixed module identities.
func TestProjectModuleRenamePreflightWriteFailures(t *testing.T) {
	t.Parallel()
	for _, test := range []string{"changed", "mode changed", "read-only", "deleted", "stage failure"} {
		t.Run(test, func(t *testing.T) {
			root := moduleRenameFixture(t)
			if test == "read-only" {
				if err := os.Chmod(filepath.Join(root, "main.go"), 0o444); err != nil {
					t.Fatal(err)
				}
			}
			plan, err := planProjectModuleRename(root, "example.org/new")
			if err != nil {
				t.Fatal(err)
			}
			switch test {
			case "changed":
				writeModuleRenameFixture(t, root, map[string]string{"main.go": "package changed\n"})
			case "mode changed":
				if err := os.Chmod(filepath.Join(root, "main.go"), 0o444); err != nil {
					t.Fatal(err)
				}
			case "deleted":
				if err := os.Remove(filepath.Join(root, "main.go")); err != nil {
					t.Fatal(err)
				}
			case "stage failure":
				plan.files = append(plan.files, moduleRenameFile{path: "missing/file.go"})
			}
			before := moduleRenameSnapshot(t, root)
			if err := plan.apply(os.Rename); err == nil {
				t.Fatal("apply unexpectedly succeeded")
			}
			if !reflect.DeepEqual(before, moduleRenameSnapshot(t, root)) {
				t.Fatal("preflight failure changed files")
			}
		})
	}
}

