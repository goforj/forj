// TestProjectModuleRenameRejectsMissingAndSpecialFiles prevents partial rewrites and writes through links.
func TestProjectModuleRenameRejectsMissingAndSpecialFiles(t *testing.T) {
	t.Parallel()
	for _, name := range []string{".goforj.yml", "go.mod", "main.go", "nested/go.mod"} {
		t.Run(name, func(t *testing.T) {
			root := moduleRenameFixture(t)
			outside := filepath.Join(t.TempDir(), "outside")
			if err := os.WriteFile(outside, []byte("outside unchanged"), 0o600); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(root, name)
			_ = os.Remove(path)
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.Symlink(outside, path); err != nil {
				t.Skipf("symlinks unavailable: %v", err)
			}
			_, err := planProjectModuleRename(root, "example.org/new")
			if err == nil || !strings.Contains(err.Error(), "regular file") {
				t.Fatalf("error = %v", err)
			}
			if got := readMakeAppTestFile(t, outside); got != "outside unchanged" {
				t.Fatal("symlink target changed")
			}
		})
	}
	for _, name := range []string{".goforj.yml", "go.mod"} {
		root := moduleRenameFixture(t)
		if err := os.Remove(filepath.Join(root, name)); err != nil {
			t.Fatal(err)
		}
		if _, err := planProjectModuleRename(root, "example.org/new"); !errors.Is(err, fs.ErrNotExist) {
			t.Fatalf("missing %s: %v", name, err)
		}
	}
}

