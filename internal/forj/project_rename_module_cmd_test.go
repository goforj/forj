// moduleRenameReadFunc lets a test model an editor changing the project while a prompt waits for input.
type moduleRenameReadFunc func([]byte) (int, error)

// Read invokes the test's input callback using the ordinary console reader contract.
func (f moduleRenameReadFunc) Read(data []byte) (int, error) { return f(data) }

